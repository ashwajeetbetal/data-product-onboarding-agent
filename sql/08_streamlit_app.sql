-- Phase 8: steward approval queue (Streamlit in Snowflake, container runtime, restricted caller's rights)
-- App code: streamlit/streamlit_app.py

-- Caller grants: what the app (owned by GOV_ADMIN) may do with the viewer's privileges (needs MANAGE CALLER GRANTS)
USE ROLE ACCOUNTADMIN;
GRANT CALLER USAGE ON DATABASE HACKATHON_DB TO ROLE GOV_ADMIN;
GRANT CALLER USAGE ON SCHEMA HACKATHON_DB.GOV TO ROLE GOV_ADMIN;
GRANT CALLER USAGE ON WAREHOUSE GOV_WH TO ROLE GOV_ADMIN;
GRANT CALLER SELECT ON TABLE HACKATHON_DB.GOV.PENDING_FIXES TO ROLE GOV_ADMIN;
GRANT CALLER UPDATE ON TABLE HACKATHON_DB.GOV.PENDING_FIXES TO ROLE GOV_ADMIN;
GRANT CALLER SELECT ON TABLE HACKATHON_DB.GOV.CONTRACTS TO ROLE GOV_ADMIN;
GRANT CALLER UPDATE ON TABLE HACKATHON_DB.GOV.CONTRACTS TO ROLE GOV_ADMIN;
GRANT CALLER SELECT ON TABLE HACKATHON_DB.GOV.CONTRACT_FIELDS TO ROLE GOV_ADMIN;
GRANT CALLER UPDATE ON TABLE HACKATHON_DB.GOV.CONTRACT_FIELDS TO ROLE GOV_ADMIN;
GRANT CALLER SELECT ON TABLE HACKATHON_DB.GOV.RULEBOOK TO ROLE GOV_ADMIN;
GRANT CALLER SELECT ON TABLE HACKATHON_DB.GOV.AUDIT_LOG TO ROLE GOV_ADMIN;
GRANT CALLER INSERT ON TABLE HACKATHON_DB.GOV.AUDIT_LOG TO ROLE GOV_ADMIN;
GRANT CALLER USAGE ON PROCEDURE HACKATHON_DB.GOV.APPROVE_FIX(STRING) TO ROLE GOV_ADMIN;
GRANT CALLER USAGE ON PROCEDURE HACKATHON_DB.GOV.REJECT_FIX(STRING, STRING) TO ROLE GOV_ADMIN;
GRANT CALLER USAGE ON PROCEDURE HACKATHON_DB.GOV.APPLY_APPROVED_FIXES(STRING) TO ROLE GOV_ADMIN;
GRANT CALLER USAGE ON PROCEDURE HACKATHON_DB.GOV.PROMOTE_DATASET(STRING) TO ROLE GOV_ADMIN;
GRANT USAGE ON COMPUTE POOL SYSTEM_COMPUTE_POOL_CPU TO ROLE GOV_ADMIN;
GRANT SELECT ON TABLE HACKATHON_DB.GOV.RULEBOOK TO ROLE GOV_STEWARD;
SHOW CALLER GRANTS TO ROLE GOV_ADMIN;

USE ROLE GOV_ADMIN;
CREATE STAGE IF NOT EXISTS HACKATHON_DB.GOV.APP_STAGE DIRECTORY = (ENABLE = TRUE);
PUT file://streamlit/streamlit_app.py @HACKATHON_DB.GOV.APP_STAGE/approval_queue AUTO_COMPRESS = FALSE OVERWRITE = TRUE;

CREATE OR REPLACE STREAMLIT HACKATHON_DB.GOV.APPROVAL_QUEUE
  FROM '@HACKATHON_DB.GOV.APP_STAGE/approval_queue'
  MAIN_FILE = 'streamlit_app.py'
  QUERY_WAREHOUSE = GOV_WH
  RUNTIME_NAME = 'SYSTEM$ST_CONTAINER_RUNTIME_PY3_11'
  COMPUTE_POOL = SYSTEM_COMPUTE_POOL_CPU
  TITLE = 'Steward approval queue';
GRANT USAGE ON STREAMLIT HACKATHON_DB.GOV.APPROVAL_QUEUE TO ROLE GOV_STEWARD;
SHOW STREAMLITS LIKE 'APPROVAL_QUEUE' IN ACCOUNT;

-- Check: USER3 (default role GOV_STEWARD) approves one fix in the app; the audit row shows USER3
SELECT ts, actor, action, fix_id, details:role::STRING AS role
FROM HACKATHON_DB.GOV.AUDIT_LOG WHERE action = 'APPROVE_FIX' ORDER BY audit_id DESC LIMIT 5;

-- Fix (13:20): a pyproject.toml added to the stage after deploy made the container resolve packages on PyPI,
-- which fails without an external access integration. The app uses only pre-installed packages, so remove it
-- and recreate the app from the clean stage (CREATE OR REPLACE drops grants: re-grant USAGE).
REMOVE @HACKATHON_DB.GOV.APP_STAGE/approval_queue/pyproject.toml;
CREATE OR REPLACE STREAMLIT HACKATHON_DB.GOV.APPROVAL_QUEUE
  FROM '@HACKATHON_DB.GOV.APP_STAGE/approval_queue'
  MAIN_FILE = 'streamlit_app.py'
  QUERY_WAREHOUSE = GOV_WH
  RUNTIME_NAME = 'SYSTEM$ST_CONTAINER_RUNTIME_PY3_11'
  COMPUTE_POOL = SYSTEM_COMPUTE_POOL_CPU
  TITLE = 'Steward approval queue';
GRANT USAGE ON STREAMLIT HACKATHON_DB.GOV.APPROVAL_QUEUE TO ROLE GOV_STEWARD;

-- Fix (13:25): this container runtime requires a pyproject.toml, and resolving it needs PyPI access.
-- Supersedes the 13:20 removal above. PyPI-only EAI on Snowflake's managed rule (needs ACCOUNTADMIN).
USE ROLE ACCOUNTADMIN;
CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS PYPI_ACCESS_INTEGRATION
  ALLOWED_NETWORK_RULES = (snowflake.external_access.pypi_rule)
  ENABLED = TRUE
  COMMENT = 'PyPI only, for the steward approval queue Streamlit container runtime';
GRANT USAGE ON INTEGRATION PYPI_ACCESS_INTEGRATION TO ROLE GOV_ADMIN;

USE ROLE GOV_ADMIN;
PUT file://streamlit/pyproject.toml @HACKATHON_DB.GOV.APP_STAGE/approval_queue AUTO_COMPRESS = FALSE OVERWRITE = TRUE;
CREATE OR REPLACE STREAMLIT HACKATHON_DB.GOV.APPROVAL_QUEUE
  FROM '@HACKATHON_DB.GOV.APP_STAGE/approval_queue'
  MAIN_FILE = 'streamlit_app.py'
  QUERY_WAREHOUSE = GOV_WH
  RUNTIME_NAME = 'SYSTEM$ST_CONTAINER_RUNTIME_PY3_11'
  COMPUTE_POOL = SYSTEM_COMPUTE_POOL_CPU
  EXTERNAL_ACCESS_INTEGRATIONS = (PYPI_ACCESS_INTEGRATION)
  TITLE = 'Steward approval queue';
GRANT USAGE ON STREAMLIT HACKATHON_DB.GOV.APPROVAL_QUEUE TO ROLE GOV_STEWARD;
