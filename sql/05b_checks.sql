-- Phase 5b checks (procedures are in 05b_approval_apply_promote_reset.sql)
USE ROLE GOV_ADMIN;
CALL HACKATHON_DB.GOV.RESET_DEMO();
CALL HACKATHON_DB.GOV.PARSE_CONTRACT('C-LAB-001');
CALL HACKATHON_DB.GOV.PROFILE_COLUMNS('HACKATHON_DB.STAGING.LAB_RESULTS');
CALL HACKATHON_DB.GOV.CLASSIFY_TRACK('C-LAB-001');
CALL HACKATHON_DB.GOV.CHECK_PROVENANCE('HACKATHON_DB.STAGING.LAB_RESULTS');
CALL HACKATHON_DB.GOV.PROPOSE_FIXES('C-LAB-001');   -- T-OWNER / T-SLA = NEEDS_OWNER_INPUT

USE SECONDARY ROLES NONE;
USE ROLE GOV_DATA_OWNER;
CALL HACKATHON_DB.GOV.APPROVE_FIX('FX-5ED577F935');                     -- expect: Unknown user-defined function

USE ROLE GOV_STEWARD;
CALL HACKATHON_DB.GOV.APPROVE_FIX('FX-10569E4ADA');                     -- expect ERROR: NEEDS_OWNER_INPUT
CALL HACKATHON_DB.GOV.APPLY_APPROVED_FIXES('FX-5ED577F935');            -- expect ERROR: not APPROVED
CALL HACKATHON_DB.GOV.PROMOTE_DATASET('C-LAB-001');                     -- expect ERROR: open fixes

USE ROLE GOV_DATA_OWNER;
CALL HACKATHON_DB.GOV.PROPOSE_FIXES('C-LAB-001', '{"owner": "lab.ops@example.com", "freshness_sla_hours": 24}');

USE ROLE GOV_STEWARD;
CALL HACKATHON_DB.GOV.APPROVE_FIX('FX-10569E4ADA');
CALL HACKATHON_DB.GOV.APPROVE_FIX('FX-DCBE01AF17');
CALL HACKATHON_DB.GOV.APPROVE_FIX('FX-5ED577F935');
CALL HACKATHON_DB.GOV.APPROVE_FIX('FX-F98DC3DBFD');
CALL HACKATHON_DB.GOV.APPROVE_FIX('FX-1661B99582');
-- approver and audit actor are the current user
SELECT CURRENT_USER() AS session_user, p.fix_id, p.approved_by, p.approved_hash = p.fix_hash AS hash_ok, a.actor AS audit_actor
FROM HACKATHON_DB.GOV.PENDING_FIXES p
JOIN HACKATHON_DB.GOV.AUDIT_LOG a ON a.fix_id = p.fix_id AND a.action = 'APPROVE_FIX' ORDER BY p.fix_id;

CALL HACKATHON_DB.GOV.APPLY_APPROVED_FIXES('FX-1661B99582');            -- quarantine LAB-B010 (one transaction)
CALL HACKATHON_DB.GOV.APPLY_APPROVED_FIXES('FX-5ED577F935');
CALL HACKATHON_DB.GOV.APPLY_APPROVED_FIXES('FX-F98DC3DBFD');
CALL HACKATHON_DB.GOV.APPLY_APPROVED_FIXES('FX-10569E4ADA');
CALL HACKATHON_DB.GOV.APPLY_APPROVED_FIXES('FX-DCBE01AF17');
CALL HACKATHON_DB.GOV.PROMOTE_DATASET('C-LAB-001');

USE ROLE GOV_ADMIN;
-- expect 450/0, 50/50, 450/0
SELECT 'STAGING.LAB_RESULTS' t, COUNT(*) n, COUNT_IF(batch_id = 'LAB-B010') b010 FROM HACKATHON_DB.STAGING.LAB_RESULTS
UNION ALL SELECT 'QUARANTINE_LAB_RESULTS', COUNT(*), COUNT_IF(batch_id = 'LAB-B010') FROM HACKATHON_DB.STAGING.QUARANTINE_LAB_RESULTS
UNION ALL SELECT 'PROD.LAB_RESULTS', COUNT(*), COUNT_IF(batch_id = 'LAB-B010') FROM HACKATHON_DB.PROD.LAB_RESULTS;

USE ROLE GOV_CONSUMER;
SELECT COUNT(*) n, COUNT_IF(patient_id = 'PT-******') masked FROM HACKATHON_DB.PROD.LAB_RESULTS;  -- expect 450 / 450

USE ROLE GOV_ADMIN;
CALL HACKATHON_DB.GOV.RESET_DEMO();   -- undo in reverse apply order
-- expect 500, 0, 0 policies, 0 PROD tables, 0 pending, 0 non-SUBMITTED, AUDIT_LOG kept
SELECT
 (SELECT COUNT(*) FROM HACKATHON_DB.STAGING.LAB_RESULTS) AS lab_rows,
 (SELECT COUNT(*) FROM HACKATHON_DB.STAGING.QUARANTINE_LAB_RESULTS) AS quarantine_rows,
 (SELECT COUNT(*) FROM TABLE(HACKATHON_DB.INFORMATION_SCHEMA.POLICY_REFERENCES(REF_ENTITY_NAME => 'HACKATHON_DB.STAGING.LAB_RESULTS', REF_ENTITY_DOMAIN => 'table'))) AS policies_on_lab,
 (SELECT COUNT(*) FROM HACKATHON_DB.INFORMATION_SCHEMA.TABLES WHERE table_schema = 'PROD') AS prod_tables,
 (SELECT COUNT(*) FROM HACKATHON_DB.GOV.PENDING_FIXES) AS pending,
 (SELECT COUNT_IF(status <> 'SUBMITTED') FROM HACKATHON_DB.GOV.CONTRACTS) AS non_submitted,
 (SELECT COUNT(*) FROM HACKATHON_DB.GOV.AUDIT_LOG WHERE action = 'RESET') AS reset_rows;
