-- Phase 1 event additions (pre-event objects are only verified, never recreated).
-- Demo users: USER = consumer, USER2 = data owner (submits), USER3 = steward (approves).
USE ROLE GOV_ADMIN;

-- Users, roles and account settings need ACCOUNTADMIN
USE ROLE ACCOUNTADMIN;

GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE GOV_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE GOV_DATA_OWNER;
GRANT USAGE ON DATABASE HACKATHON_DB TO ROLE GOV_DATA_OWNER;
GRANT USAGE ON SCHEMA HACKATHON_DB.GOV TO ROLE GOV_DATA_OWNER;
GRANT USAGE ON WAREHOUSE GOV_WH TO ROLE GOV_DATA_OWNER;

GRANT ROLE GOV_CONSUMER   TO USER "USER";
GRANT ROLE GOV_DATA_OWNER TO USER "USER2";
GRANT ROLE GOV_STEWARD    TO USER "USER3";
GRANT ROLE GOV_ADMIN      TO USER "USER";
GRANT ROLE GOV_ADMIN      TO USER "USER2";
GRANT ROLE GOV_ADMIN      TO USER "USER3";

ALTER USER "USER"  SET DEFAULT_ROLE = GOV_CONSUMER   DEFAULT_WAREHOUSE = GOV_WH DEFAULT_SECONDARY_ROLES = ();
ALTER USER "USER2" SET DEFAULT_ROLE = GOV_DATA_OWNER DEFAULT_WAREHOUSE = GOV_WH DEFAULT_SECONDARY_ROLES = ();
ALTER USER "USER3" SET DEFAULT_ROLE = GOV_STEWARD    DEFAULT_WAREHOUSE = GOV_WH DEFAULT_SECONDARY_ROLES = ();

USE ROLE GOV_ADMIN;
