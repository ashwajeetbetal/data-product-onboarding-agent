-- 01_setup.sql
-- Run in a Snowsight worksheet, top to bottom, as ACCOUNTADMIN.
-- Prepared for user USER2 on the hackathon account.

USE ROLE ACCOUNTADMIN;

-- 1. Cross-region inference: already ANY_REGION on this account, so this line is a harmless no-op
ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'ANY_REGION';

-- 2. Cortex AI Guardrails: prompt-injection protection for Cortex Agents and CoWork
--    (needs Enterprise Edition or higher; if this errors, note it and carry on)
ALTER ACCOUNT SET AI_SETTINGS = $$
  guardrails:
    advanced_prompt_injection:
      - enabled: true
$$;
SHOW PARAMETERS LIKE 'AI_SETTINGS' IN ACCOUNT;

-- 3. Warehouse, database and schemas
CREATE WAREHOUSE IF NOT EXISTS GOV_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS HACKATHON_DB;
CREATE SCHEMA IF NOT EXISTS HACKATHON_DB.GOV;      -- governance objects
CREATE SCHEMA IF NOT EXISTS HACKATHON_DB.STAGING;  -- data lands here
CREATE SCHEMA IF NOT EXISTS HACKATHON_DB.PROD;     -- data is promoted here

-- 4. Roles
CREATE ROLE IF NOT EXISTS GOV_ADMIN;       -- builds everything
CREATE ROLE IF NOT EXISTS GOV_AGENT_ROLE;  -- agent actions, procedures only
CREATE ROLE IF NOT EXISTS GOV_STEWARD;     -- approves fixes
CREATE ROLE IF NOT EXISTS GOV_CONSUMER;    -- non-privileged reader for masking checks
CREATE ROLE IF NOT EXISTS GOV_DATA_OWNER;  -- lab owner who submits contracts
GRANT ROLE GOV_ADMIN TO ROLE SYSADMIN;

-- GOV_ADMIN owns the build
GRANT USAGE ON WAREHOUSE GOV_WH TO ROLE GOV_ADMIN;
GRANT ALL ON DATABASE HACKATHON_DB TO ROLE GOV_ADMIN;
-- GOV_ADMIN owns the schemas so it can grant on them without ACCOUNTADMIN
GRANT OWNERSHIP ON SCHEMA HACKATHON_DB.GOV TO ROLE GOV_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA HACKATHON_DB.STAGING TO ROLE GOV_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA HACKATHON_DB.PROD TO ROLE GOV_ADMIN COPY CURRENT GRANTS;

-- Other roles: warehouse, database and GOV schema only (object grants come later, per phase)
GRANT USAGE ON WAREHOUSE GOV_WH TO ROLE GOV_AGENT_ROLE;
GRANT USAGE ON WAREHOUSE GOV_WH TO ROLE GOV_STEWARD;
GRANT USAGE ON WAREHOUSE GOV_WH TO ROLE GOV_CONSUMER;
GRANT USAGE ON WAREHOUSE GOV_WH TO ROLE GOV_DATA_OWNER;

GRANT USAGE ON DATABASE HACKATHON_DB TO ROLE GOV_AGENT_ROLE;
GRANT USAGE ON DATABASE HACKATHON_DB TO ROLE GOV_STEWARD;
GRANT USAGE ON DATABASE HACKATHON_DB TO ROLE GOV_CONSUMER;
GRANT USAGE ON DATABASE HACKATHON_DB TO ROLE GOV_DATA_OWNER;

GRANT USAGE ON SCHEMA HACKATHON_DB.GOV TO ROLE GOV_AGENT_ROLE;
GRANT USAGE ON SCHEMA HACKATHON_DB.GOV TO ROLE GOV_STEWARD;
GRANT USAGE ON SCHEMA HACKATHON_DB.GOV TO ROLE GOV_CONSUMER;
GRANT USAGE ON SCHEMA HACKATHON_DB.GOV TO ROLE GOV_DATA_OWNER;

-- Cortex access
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE GOV_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE GOV_AGENT_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE GOV_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE GOV_STEWARD;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER TO ROLE GOV_DATA_OWNER;

-- 5. Give yourself every role and a default warehouse
GRANT ROLE GOV_ADMIN      TO USER "USER2";
GRANT ROLE GOV_AGENT_ROLE TO USER "USER2";
GRANT ROLE GOV_STEWARD    TO USER "USER2";
GRANT ROLE GOV_CONSUMER   TO USER "USER2";
GRANT ROLE GOV_DATA_OWNER TO USER "USER2";
ALTER USER "USER2" SET DEFAULT_WAREHOUSE = GOV_WH;
-- Only the role you are acting as counts. Without this, secondary roles (ALL) let any session use
-- steward and admin privileges, which breaks separation of duties and unmasks patient IDs.
ALTER USER "USER2" SET DEFAULT_SECONDARY_ROLES = ();

-- 6. Check: Claude answers from inside Snowflake
USE ROLE GOV_ADMIN;
USE WAREHOUSE GOV_WH;
SELECT AI_COMPLETE('claude-sonnet-5', 'Reply with one word: ready') AS claude_check;
-- If claude-sonnet-5 is not available, try 'claude-sonnet-4-6'.
